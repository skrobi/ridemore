            <li>przewidywany dystans i wymagania wobec uczestników,</li>
            <li>zasady uczestnictwa,</li>
            <li>informację o ewentualnych opłatach,</li>
            <li>zakres świadczeń zawartych w cenie,</li>
            <li>zasady rezygnacji oraz zwrotów, jeżeli mają zastosowanie.</li>
        </ul>

        <p>
            Organizator ponosi odpowiedzialność za:
        </p>

        <ul>
            <li>przygotowanie i realizację wydarzenia,</li>
            <li>kontakt z uczestnikami,</li>
            <li>rozliczenia finansowe,</li>
            <li>udzielone informacje dotyczące wydarzenia,</li>
            <li>zapewnienie wymaganych prawem warunków organizacji wydarzenia.</li>
        </ul>


