            </li>
            <li>
                podszywanie się pod inne osoby lub podmioty,
            </li>
            <li>
                wykorzystywanie danych innych osób bez odpowiedniej podstawy prawnej,
            </li>
            <li>
                publikowanie treści naruszających prawa osób trzecich,
            </li>
            <li>
                podejmowanie działań mogących zakłócić funkcjonowanie Serwisu,
            </li>
            <li>
                wykorzystywanie Serwisu do działań niezgodnych z prawem.
            </li>
        </ul>

        <p>
            Administrator ma prawo usunąć treści lub ograniczyć dostęp użytkownika do
            Serwisu w przypadku naruszenia Regulaminu lub obowiązujących przepisów prawa.
        </p>


