        <h2>§ 3. Charakter działania Serwisu</h2>

        <p>
            RideMore.bike jest platformą internetową umożliwiającą publikację oraz wyszukiwanie
            wydarzeń rowerowych.
        </p>

        <p>
            Serwis pełni funkcję narzędzia wspierającego społeczność rowerową poprzez:
        </p>

        <ul>
            <li>prezentowanie informacji o wydarzeniach,</li>
            <li>umożliwienie wyszukiwania wydarzeń według dostępnych kryteriów,</li>
            <li>umożliwienie zgłaszania udziału,</li>
            <li>prowadzenie list uczestników wydarzeń,</li>
            <li>ułatwienie komunikacji pomiędzy Organizatorem i Uczestnikami.</li>
        </ul>

        <p>
            RideMore.bike nie jest automatycznie organizatorem wydarzeń publikowanych
            przez użytkowników Serwisu.
        </p>

        <p>
            W przypadku wydarzeń organizowanych przez osoby lub podmioty trzecie,
            Organizatorem jest podmiot wskazany w opisie danego wydarzenia.
        </p>

        <p>
            RideMore.bike nie przejmuje obowiązków Organizatora wydarzenia oraz nie odpowiada
            za sposób jego realizacji.
        </p>


