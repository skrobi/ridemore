        <h2>§ 11. Aplikacja mobilna</h2>

        <p>
            Aplikacja mobilna RideMore.bike wyświetla ten sam serwis co
            przeglądarka i korzysta z tego samego konta — nie jest osobnym
            zbiorem danych. Dodatkowo, wyłącznie w aplikacji, przetwarzane są:
        </p>

        <ul>

            <li>
                <strong>Lokalizacja w tle.</strong> Aplikacja śledzi dokładną
                pozycję GPS, także gdy jest zwinięta, WYŁĄCZNIE w trakcie
                nagrywania przejazdu — funkcji, którą użytkownik świadomie
                włącza i w każdej chwili może zatrzymać (widoczny wskaźnik
                nagrywania z przyciskiem „Zatrzymaj"). Poza aktywnym
                nagrywaniem aplikacja nie śledzi pozycji w tle. Zapisana trasa
                służy do wyznaczenia odkrytych pól mapy i zaliczenia
                znalezionych po drodze skarbów.
            </li>

            <li>
                <strong>Aparat.</strong> Zdjęcia zrobione aparatem trafiają
                wyłącznie tam, gdzie użytkownik świadomie je dodaje (zgłoszenie
                skarbu, galeria znalezionego miejsca) — tak samo, jakby wybrał
                plik z dysku na stronie internetowej.
            </li>

            <li>
                <strong>Powiadomienia push.</strong> Po włączeniu powiadomień
                w ustawieniach konta urządzenie otrzymuje unikalny token
                (Firebase Cloud Messaging / Apple Push Notification service),
                powiązany z kontem użytkownika, służący wyłącznie do
                dostarczania powiadomień o aktywności w serwisie (nowy skarb
                w okolicy, dołączenie do wyjazdu, nowa wiadomość). Wyłączenie
                powiadomień w ustawieniach konta zatrzymuje ich wysyłkę.
                Treść wiadomości prywatnych nigdy nie jest przenoszona do
                powiadomienia.
            </li>

        </ul>

        <p>
            <strong>Usunięcie konta w aplikacji.</strong> W ustawieniach konta
            (Moje konto → Usunięcie konta) dostępna jest funkcja samodzielnego
            zgłoszenia usunięcia konta. Powoduje ona natychmiastowe
